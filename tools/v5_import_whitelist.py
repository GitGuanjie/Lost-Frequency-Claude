#!/usr/bin/env python3
"""Generate the whitelist for the Infinite Backrooms v5 laboratory import.

The whitelist is derived from the manifest by RULE, not by hand, so it can be
regenerated and audited.  Two groups:

  code  - the laboratory itself: the new world classes, the lab scene, the
          continuity tests, the lab documentation and the lab runner scripts,
          plus the three files the v5 session genuinely modified.
  assets- the external model textures that the archive adds.  They are purely
          additive: every .glb is byte-identical to the upstream checkout.

Deliberately NOT imported: anything under levels/** or data/canon/**.  The
archive carries a different 100-level snapshot; reconciling that with the
canonical story system is a separate, explicitly staged phase.
"""

import json
import sys

manifest_path, out_path = sys.argv[1], sys.argv[2]

with open(manifest_path, encoding="utf-8") as fh:
    m = json.load(fh)

new = {i["path"] for i in m["new"]}
different = {i["path"] for i in m["different"]}

CODE_EXACT_PREFIXES = (
    "labs/",
    "core/world/ChunkWorld3D.gd",
    "core/world/ContinuityTopology.gd",
    "core/world/RegionalPlan.gd",
    "core/world/WorldAddress.gd",
    "tests/ContinuityMacroStructureTest.gd",
    "tests/ContinuityPhysicalWalkTest.gd",
    "tests/ContinuityPhysicalWalkTest.tscn",
    "tests/ContinuityRegionalPlanTest.gd",
    "tests/ContinuitySuperDistrictTest.gd",
    "tests/ContinuityTopologyTest.gd",
    "tests/test_worldlab_v2_static.py",
    "tests/test_worldlab_v3_static.py",
    "tests/test_worldlab_v4_static.py",
    "tests/test_worldlab_v5_static.py",
    "tests/static/test_continuity_patch.py",
    "docs/production/WORLD_CONTINUITY_LAB",
    "docs/production/INFINITE_BACKROOMS_V5_",
    "docs/production/NEXT_SESSION_WORLDLAB_",
    "reports/qa/INFINITE_BACKROOMS_V5_QA_REPORT.md",
    "reports/qa/continuity_physical_walk.json",
    "INFINITE_BACKROOMS_V5_HANDOFF.md",
    "README_无限回廊v5.md",
    "RUN_V5_QA_WINDOWS.bat",
    "RUN_WORLD_LAB",
    "WORLD_LAB_TEST_REPORT.md",
    "WORLD_LAB_V2_TEST_REPORT.md",
    "WORLD_LAB_V3_README_FIRST.md",
    "WORLD_LAB_V3_TEST_REPORT.md",
    "WORLD_LAB_V4_README_FIRST.md",
    "WORLD_LAB_V4_TEST_REPORT.md",
)

# The three files the v5 session genuinely changed (verified by content diff;
# every other "different" file in the manifest is a CRLF/LF or .uid delta).
CODE_MODIFIED = (
    "core/world/ChunkWorld.gd",
    "ui/MainMenu.gd",
    "ui/Overlay.gd",
)

code = sorted(p for p in new if p.startswith(CODE_EXACT_PREFIXES))
code += [p for p in CODE_MODIFIED if p in different]

assets = sorted(p for p in new if p.startswith("assets/external/models/"))

whitelist = {
    "note": "Generated by tools/v5_import_whitelist.py from the import manifest.",
    "protected": ["levels/", "data/canon/"],
    "groups": {
        "code": code,
        "assets": assets,
    },
    "files": code + assets,
}

with open(out_path, "w", encoding="utf-8") as fh:
    json.dump(whitelist, fh, indent=2, ensure_ascii=False)

print("code=%d assets=%d total=%d" % (len(code), len(assets), len(whitelist["files"])))
for p in code:
    print("  code   " + p)
